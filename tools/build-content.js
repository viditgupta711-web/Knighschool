n += write("endgames.js",     "lessons", endgames,      "Endgame lessons (tier 10).");
n += write("tips.js",         "lessons", tips,          "Practical play and study habits (tier 11).");
n += write("puzzles.js",      "puzzles", puzzles,       "Extra tactics puzzles.");

